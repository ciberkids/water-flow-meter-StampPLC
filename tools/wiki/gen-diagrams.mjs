#!/usr/bin/env node
/**
 * Generates the navigation diagrams FROM the dataset the firmware actually runs.
 *
 *   node tools/wiki/gen-diagrams.mjs           print what it would write
 *   node tools/wiki/gen-diagrams.mjs --write   write docs/diagrams/*.mermaid
 *
 * WHY GENERATED.
 *
 * The hand-drawn versions of these two diagrams were wrong in every structural detail by the time
 * anyone looked at them: a flat `C1 Modbus ID .. C7 Sensor Select` ring that had become three groups,
 * info pages numbered P1..P7 that had been renumbered P0..P6, a sensor submenu with no calibration
 * branch, and gestures that three separate decisions had since changed. None of it was noticed,
 * because a diagram has no test and no reader who knows it is stale.
 *
 * The structure has exactly one home — `web/mockup/src/data/screens.json`, itself generated — so these
 * are a view of it. Re-running is how they stay true, and the ring walk below fails loudly rather than
 * drawing a plausible tree if the dataset's own navigation is inconsistent.
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const repoRoot = path.join(import.meta.dirname, "..", "..");
const dataset = JSON.parse(
  fs.readFileSync(path.join(repoRoot, "web", "mockup", "src", "data", "screens.json"), "utf-8")
);

const byId = new Map(dataset.screens.map((s) => [s.id, s]));
const flowsOf = (screen, actionId) =>
  (screen.flows ?? []).filter((f) => f.actionId === actionId && f.targetScreenId);

const nextOf = (screen) => flowsOf(screen, "ui.action.page.next")[0]?.targetScreenId;
const descendOf = (screen) => flowsOf(screen, "ui.action.nav.descend")[0]?.targetScreenId;

/** Which screen descends INTO each screen — the parent of a level, not of a screen. */
const enteredFrom = new Map();
for (const screen of dataset.screens) {
  const target = descendOf(screen);
  if (target) enteredFrom.set(target, screen.id);
}

/**
 * The ring a screen belongs to, walked through `page.next` until it closes.
 *
 * Throws rather than truncating: a ring that does not close is a level an operator can walk into and
 * not out of, which is the bug this walk would otherwise hide by drawing the part that made sense.
 */
function ringFrom(startId) {
  const ring = [];
  const seen = new Set();
  let cursor = startId;
  while (cursor && !seen.has(cursor)) {
    seen.add(cursor);
    ring.push(cursor);
    cursor = nextOf(byId.get(cursor));
  }
  if (cursor !== startId && cursor !== undefined) {
    throw new Error(`the ring from ${startId} re-enters at ${cursor} instead of closing`);
  }
  return ring;
}

/** Every distinct ring in the dataset, keyed by its first member. */
const rings = [];
const claimed = new Set();
for (const screen of dataset.screens) {
  if (claimed.has(screen.id)) continue;
  const ring = ringFrom(screen.id);
  if (ring.length < 2) continue; // a screen with no siblings is not a level
  ring.forEach((id) => claimed.add(id));
  rings.push(ring);
}

/**
 * Which screens descend into a ring — plural, deliberately.
 *
 * `enteredFrom` is keyed by target, so a level entered from eight places keeps only the last writer:
 * the sensor-settings level came out labelled "Level: SEN8 - Sensor 8", which reads as Sensor 8's own
 * settings when it is in fact ONE level shared by all eight, whose content depends on which sensor was
 * selected on the way in. That is the single most surprising thing about the tree, so the diagram has
 * to say it rather than round it off to the last entry.
 */
function ringEntries(ring) {
  const members = new Set(ring);
  const entries = [];
  for (const screen of dataset.screens) {
    const target = descendOf(screen);
    if (target && members.has(target)) entries.push(screen.id);
  }
  return entries;
}

const nameOf = (id) => (byId.get(id)?.name ?? id).replace(/—/g, "-");

/** How to title a level's box, given everything that descends into it. */
function ringTitle(ring, rootLabel) {
  const entries = ringEntries(ring);
  if (entries.length === 0) return rootLabel;
  if (entries.length === 1) return `Level: ${nameOf(entries[0])}`;
  return `Level: shared by ${nameOf(entries[0])} .. ${nameOf(entries[entries.length - 1])} ` +
         `(${entries.length} entries, content follows the selected sensor)`;
}

const label = (id) => {
  const screen = byId.get(id);
  const name = (screen?.name ?? id).replace(/"/g, "'").replace(/—/g, "-");
  const gate = screen?.visibleWhen
    ? `<br/><i>only when ${screen.visibleWhen.binding} = ${screen.visibleWhen.equals}</i>`
    : "";
  return `${name}${gate}`;
};

const nodeId = (id) => id.replace(/[^A-Za-z0-9]/g, "_");

/* ── Diagram 1: the navigation tree ───────────────────────────────────────────────────────────── */
function navigationTree() {
  const out = [];
  out.push("%% GENERATED by tools/wiki/gen-diagrams.mjs from web/mockup/src/data/screens.json.");
  out.push("%% Do not edit. Re-run the generator; the dataset is the only home for this structure.");
  out.push("%%");
  out.push("%% One box per screen, grouped by the LEVEL it belongs to. A solid arrow is ENTER");
  out.push("%% descending into a level; every screen inside a level is reachable from its siblings");
  out.push("%% with UP and DOWN, which is left undrawn because it holds everywhere and drawing it");
  out.push("%% would bury the part that varies.");
  out.push("flowchart TB");

  rings.forEach((ring, index) => {
    const title = ringTitle(ring, "Root ring (info pages)");
    out.push(`    subgraph L${index}["${title}"]`);
    out.push("        direction TB");
    for (const id of ring) {
      out.push(`        ${nodeId(id)}["${label(id)}"]`);
    }
    out.push("    end");
  });

  // Descend edges, drawn after the subgraphs so mermaid places the levels first.
  for (const screen of dataset.screens) {
    const target = descendOf(screen);
    if (!target) continue;
    // Editors are a screen's own value editor, not a level: one box each would double the diagram.
    if (target.endsWith("-edit")) continue;
    out.push(`    ${nodeId(screen.id)} -- ENTER --> ${nodeId(target)}`);
  }

  return out.join("\n") + "\n";
}

/* ── Diagram 2: the configuration tree, on its own ────────────────────────────────────────────── */
function configurationTree() {
  const out = [];
  out.push("%% GENERATED by tools/wiki/gen-diagrams.mjs from web/mockup/src/data/screens.json.");
  out.push("%% Do not edit — re-run the generator.");
  out.push("%%");
  out.push("%% Configuration, which is three GROUPS rather than the flat C1..C8 list this diagram");
  out.push("%% used to show. `.V` suffixes are value editors, reached with ENTER from the setting");
  out.push("%% page and left with ENTER (commit) or held ENTER (discard).");
  out.push("flowchart TB");

  const configRings = rings.filter((ring) => ring.some((id) => id.startsWith("config-")));
  configRings.forEach((ring, index) => {
    const title = ringTitle(ring, "Configuration root");
    out.push(`    subgraph C${index}["${title}"]`);
    out.push("        direction TB");
    for (const id of ring) {
      const editor = descendOf(byId.get(id));
      const suffix = editor && editor.endsWith("-edit") ? "<br/><i>ENTER opens its editor</i>" : "";
      out.push(`        ${nodeId(id)}["${label(id)}${suffix}"]`);
    }
    out.push("    end");
  });

  for (const screen of dataset.screens) {
    if (!screen.id.startsWith("config-")) continue;
    const target = descendOf(screen);
    if (!target || target.endsWith("-edit")) continue;
    out.push(`    ${nodeId(screen.id)} -- ENTER --> ${nodeId(target)}`);
  }

  return out.join("\n") + "\n";
}

const outputs = {
  "docs/diagrams/ui_navigation_tree.mermaid": navigationTree(),
  "docs/diagrams/ui_config_layout.mermaid": configurationTree()
};

if (process.argv.includes("--write")) {
  for (const [file, content] of Object.entries(outputs)) {
    fs.writeFileSync(path.join(repoRoot, file), content);
    console.error(`wrote ${file} (${content.split("\n").length} lines)`);
  }
} else {
  for (const [file, content] of Object.entries(outputs)) {
    console.log(`──── ${file} ────`);
    console.log(content);
  }
}
